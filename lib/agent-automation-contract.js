  [AGENT_RUN_STATES.SCHEDULED]: [AGENT_RUN_STATES.RESEARCHING, AGENT_RUN_STATES.RESEARCH_FAILED],
  [AGENT_RUN_STATES.RESEARCHING]: [AGENT_RUN_STATES.RESEARCH_READY, AGENT_RUN_STATES.RESEARCH_FAILED],
